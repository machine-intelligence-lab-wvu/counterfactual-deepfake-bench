"""REPORT.md for one snapshot: settings, coverage, every table and figure, and observations
stated as facts with numbers. Generated by eval.aggregate; nothing here is hand-edited."""
import os

import numpy as np
import pandas as pd

GEN_LABEL = {"ltx23": "LTX 2.3", "wan22": "Wan 2.2", "hunyuan15": "HunyuanVideo 1.5", "all": "all"}


def _md(df, cols=None, n=None, fmt="{:.3f}"):
    if df is None or df.empty:
        return "_empty_\n"
    d = df[cols] if cols else df
    if n:
        d = d.head(n)
    d = d.copy()
    for c in d.columns:
        if pd.api.types.is_float_dtype(d[c]):
            d[c] = d[c].map(lambda v: "" if pd.isna(v) else fmt.format(v))
    return d.to_markdown(index=False) + "\n"


def _ci(r, k="estimate"):
    return f"{r[k]:.3f} [{r['ci_lo']:.3f}, {r['ci_hi']:.3f}]"


def observations(T, thr):
    obs = []
    sb = T["score_by_breakdown"]
    ov = sb[(sb["factor"] == "overall") & (sb["generator"] != "all")]
    for r in ov.itertuples():
        obs.append(f"{GEN_LABEL.get(r.generator, r.generator)}: mean score {r.estimate:.3f} "
                   f"[{r.ci_lo:.3f}, {r.ci_hi:.3f}], median {r.median:.3f}, n = {r.n}.")
    dr = T["provisional_detection_rate"]
    for r in dr[(dr["factor"] == "overall")].itertuples():
        obs.append(f"Provisional detection rate (score >= {thr}), {GEN_LABEL.get(r.generator, r.generator)}: "
                   f"{100 * r.estimate:.1f}% [{100 * r.ci_lo:.1f}, {100 * r.ci_hi:.1f}].")
    g = T["subgroup_gap_score"]
    for attr in ["race", "gender", "age_band", "cell"]:
        ga = g[(g["attribute"] == attr) & (g["generator"] != "all")]
        if ga.empty:
            continue
        r = ga.sort_values("gap", ascending=False).iloc[0]
        obs.append(f"Largest {attr.replace('_', ' ')} score gap: {GEN_LABEL.get(r.generator)} "
                   f"{r.gap:.3f} [{r.ci_lo:.3f}, {r.ci_hi:.3f}] ({r.max_level} {r.max_mean:.3f} vs "
                   f"{r.min_level} {r.min_mean:.3f}).")
    sc = g[(g["attribute"].isin(["setting", "lighting", "behavior", "camera", "duration_nominal"]))
           & (g["generator"] == "all")].sort_values("gap", ascending=False)
    if not sc.empty:
        r = sc.iloc[0]
        obs.append(f"Largest scene-factor gap (all generators): {r.attribute} {r.gap:.3f} "
                   f"[{r.ci_lo:.3f}, {r.ci_hi:.3f}] ({r.max_level} vs {r.min_level}).")
    an = T.get("factor_anova")
    if an is not None and not an.empty:
        a = an[an["factor"] != "Residual"].sort_values("partial_eta2", ascending=False)
        top = ", ".join(f"{r.factor} {r.partial_eta2:.3f}" for r in a.head(3).itertuples())
        res = an[an["factor"] == "Residual"]["ss_share"]
        obs.append(f"Largest partial eta squared: {top}; residual holds "
                   f"{100 * float(res.iloc[0]):.1f}% of total SS.")
    cf = T["cf_spread"]
    for r in cf.itertuples():
        obs.append(f"CF spread, {GEN_LABEL.get(r.generator)}: {r.cf_spread:.3f} "
                   f"[{r.ci_lo:.3f}, {r.ci_hi:.3f}] over {r.n_groups} groups (max {r.max:.3f}).")
    fr = T["provisional_flip_rate"]
    for r in fr.itertuples():
        obs.append(f"Provisional flip rate, {GEN_LABEL.get(r.generator)}: {100 * r.flip_rate:.1f}% "
                   f"of {r.n_groups} groups [{100 * r.ci_lo:.1f}, {100 * r.ci_hi:.1f}].")
    return obs


def write_report(snap, meta, T, figs, det, spec):
    thr = meta["threshold"]
    L = [f"# {det.name} / {meta['view']}: snapshot {meta['snapshot']}\n"]
    if det.report_note:
        L.append(f"> **Detector training data.** {det.report_note}\n")
    L.append("> **Provisional threshold.** Every detection rate and flip rate below uses the "
             f"detector's default threshold ({thr}; {meta['threshold_source']}). They will be "
             "replaced by the 5%-real-FPR threshold once reals exist (section 6.3).\n")
    L.append("## Settings\n")
    s = pd.DataFrame([
        ("detector", f"{det.name} {meta['detector']['detector_version']}"),
        ("checkpoint_sha256", meta["detector"]["checkpoint_sha256"]),
        ("view", f"{meta['view']} (view_hash {meta['view_hash']})"),
        ("ffmpeg", meta["ffmpeg"]),
        ("batches", ", ".join(meta["batches"])),
        ("inclusion set", f"{meta['inclusion_set']} (technical QC pass AND face QC pass)"
         if meta["inclusion_set"] == "primary" else meta["inclusion_set"]),
        ("bootstrap", f"{meta['bootstrap']['B']} resamples of whole counterfactual groups, "
                      f"seed {meta['bootstrap']['seed']}, 95% percentile intervals"),
        ("git commit", meta["git_commit"]), ("created", meta["created"])],
        columns=["setting", "value"])
    L.append(s.to_markdown(index=False) + "\n")
    L.append("Detector preprocessing on top of the view:\n")
    L.append(pd.DataFrame([(k, str(v)) for k, v in det.preprocess_spec.items()],
                          columns=["field", "value"]).to_markdown(index=False) + "\n")

    L.append("## Coverage\n")
    L.append(_md(T["inclusion"], fmt="{:.0f}"))
    if "window_shift" in T:
        L.append("face512 window placement (fixed window at the median YuNet face centre, "
                 "shifted inward at frame edges). The scaled frame is exactly 512 px on its short "
                 "side, so every window spans it fully and is \"shifted\" on that axis by "
                 "construction; the long-axis count is the informative one.\n")
        L.append(_md(T["window_shift"], fmt="{:.0f}"))
    L.append(f"Reals scored: {meta['n_reals']}. Fakes included: {meta['n_included_fakes']} of "
             f"{meta['n_scored']} scored ({meta['n_failed']} scoring failures).\n")

    L.append("## Observations\n")
    L += [f"- {o}" for o in observations(T, thr)]
    L.append("")

    L.append("## 6.1 Fakes only, no threshold\n")
    sb = T["score_by_breakdown"]
    L.append("### Mean score by generator\n")
    L.append(_md(sb[sb["factor"] == "overall"],
                 ["generator", "n", "n_groups", "estimate", "ci_lo", "ci_hi", "sd", "median", "q05", "q95"]))
    for f in ["race", "gender", "age_band"]:
        L.append(f"### Mean score by {f.replace('_', ' ')}\n")
        L.append(_md(sb[sb["factor"] == f], ["generator", "level", "n", "estimate", "ci_lo", "ci_hi", "median"]))
    L.append("### Mean score by scene factor (all generators pooled)\n")
    L.append(_md(sb[sb["factor"].isin(["setting", "lighting", "behavior", "camera", "duration_nominal"])
                    & (sb["generator"] == "all")], ["factor", "level", "n", "estimate", "ci_lo", "ci_hi"]))
    L.append("Per-generator scene-factor and 56-cell rows: `tables/score_by_breakdown.csv`.\n")
    L.append("### Subgroup gap (max - min of level means)\n")
    L.append(_md(T["subgroup_gap_score"], ["generator", "attribute", "n_levels", "gap", "ci_lo",
                                           "ci_hi", "max_level", "min_level"]))
    L.append("### CF spread (mean over groups of the std of score across the group's cells)\n")
    L.append(_md(T["cf_spread"]))
    L.append("### Factor attribution\n")
    L.append("OLS with every factor as a fixed effect, type-II ANOVA. `ss_share` is the factor's "
             "type-II sum of squares over the total sum of squares (type-II shares need not add to 1). "
             "Scene factors are constant within a counterfactual group, so their effects are "
             "estimated from between-group differences only.\n")
    L.append(_md(T["factor_anova"], ["factor", "df", "sum_sq", "F", "p", "partial_eta2", "ss_share"], fmt="{:.4g}"))
    if "factor_lighting_x_race" in T:
        L.append("Lighting x race interaction (added to the same OLS):\n")
        L.append(_md(T["factor_lighting_x_race"], fmt="{:.4g}"))
    L.append("Mixed model `score ~ factors + (1 | counterfactual_group)` (REML) variance components "
             "(fixed effects: `tables/factor_mixed_fixed.csv`):\n")
    L.append(_md(T["factor_mixed_variance"], fmt="{:.4g}"))

    L.append(f"## 6.2 Provisional (threshold {thr}, provisional)\n")
    dr = T["provisional_detection_rate"]
    L.append("### Detection rate by generator (provisional)\n")
    L.append(_md(dr[dr["factor"] == "overall"], ["generator", "n", "estimate", "ci_lo", "ci_hi"]))
    for f in ["race", "gender", "age_band"]:
        L.append(f"### Detection rate by {f.replace('_', ' ')} (provisional)\n")
        L.append(_md(dr[dr["factor"] == f], ["generator", "level", "n", "estimate", "ci_lo", "ci_hi"]))
    L.append("### Detection-rate gap (provisional)\n")
    L.append(_md(T["provisional_detection_gap"], ["generator", "attribute", "gap", "ci_lo", "ci_hi",
                                                  "max_level", "min_level"]))
    L.append("### Flip rate (provisional): share of groups whose clips get different decisions\n")
    L.append(_md(T["provisional_flip_rate"]))
    L.append("### Sensitivity: inclusion set\n")
    L.append(_md(T["sensitivity_inclusion_set"]))

    L.append("## 6.3 Pending until reals exist\n")
    L.append(_md(T["pending_metrics"]))

    L.append("## Figures\n")
    caps = {
        "score_distribution_by_generator": "Score distribution by generator.",
        "heatmap_mean_score_cells": "Mean score, 56 cells x generator.",
        "heatmap_detection_rate_cells_provisional": "Detection rate, 56 cells x generator (provisional threshold).",
        "subgroup_mean_score": "Mean score by race, gender, age band with 95% CI.",
        "scene_factor_mean_score": "Mean score by scene factor with 95% CI.",
        "subgroup_detection_rate_provisional": "Detection rate by subgroup (provisional threshold).",
        "cf_spread_distribution": "Distribution of per-group CF spread.",
        "flip_rate_by_generator_provisional": "Flip rate by generator (provisional threshold).",
        "factor_attribution_variance_share": "Partial eta squared by factor.",
        "example_strip": "Highest- and lowest-scoring included clips.",
    }
    for f in figs:
        L.append(f"**{caps.get(f, f)}** (`figures/{f}.pdf`)\n\n![{f}](figures/{f}.png)\n")
    L.append("## Files\n")
    L.append("`manifest_used.csv` (every clip of the active batches with render/score/inclusion "
             "flags), `scores.csv` (score per scored clip), `tables/*.csv`, `figures/*`, "
             "`snapshot_meta.json`.\n")
    with open(os.path.join(snap, "REPORT.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")
